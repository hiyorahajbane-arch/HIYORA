const LanguageContext = createContext(null);

export function TranslationProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try { return localStorage.getItem('souk_lang') || 'ar'; } catch { return 'ar'; }
  });

  const setLangWithSave = (l) => {
    setLang(l);
    try { localStorage.setItem('souk_lang', l); } catch {}
  };

  const t = useMemo(() => {
    return (key) => translations[lang]?.[key] || translations['ar']?.[key] || key;
  }, [lang]);

  const direction = useMemo(() => (lang === 'ar' ? 'rtl' : 'ltr'), [lang]);

  return (
    <LanguageContext.Provider value={{ lang, setLang: setLangWithSave, t, direction }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useTranslation() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useTranslation must be used within TranslationProvider');
  return ctx;
}
